// ---------- Language switching ----------
const STORAGE_KEY = "site-lang";

function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.documentElement.lang = lang === "zh" ? "zh-Hant" : "en";

  // Highlight the active option in the toggle
  document.querySelectorAll(".lang-switch__opt").forEach((opt) => {
    opt.classList.toggle("is-active", opt.getAttribute("data-lang") === lang);
  });

  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (e) {
    /* storage may be unavailable (e.g. file:// in some browsers) */
  }
}

function initLang() {
  let lang = "en";
  try {
    lang = localStorage.getItem(STORAGE_KEY) || "en";
  } catch (e) {
    /* ignore */
  }
  applyLang(lang);

  const switcher = document.getElementById("langSwitch");
  if (switcher) {
    switcher.addEventListener("click", () => {
      const current = document.documentElement.lang === "en" ? "en" : "zh";
      applyLang(current === "en" ? "zh" : "en");
    });
  }
}

initLang();

